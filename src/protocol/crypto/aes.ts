export class AES {

    mapleVersion: number;
    iv: Uint8Array;

    constructor(iv: Uint8Array, mapleVersion: number) {
        this.iv = iv;
        this.mapleVersion = ((mapleVersion >> 8) & 0xff) | ((mapleVersion << 8) & 0xff00);
    }

    private morphIV(iv: Uint8Array): Uint8Array {
        const key = new Uint8Array([0xf2, 0x53, 0x50, 0xc6]);
        for (let i = 0; i < 4; i++) {
            const a = iv[i] & 0xFF;
            key[0] = (key[0] + shiftKey[key[1]] - a) & 0xFF;
            key[1] = (key[1] - (key[2] ^ shiftKey[a])) & 0xFF;
            key[2] = (key[2] ^ (shiftKey[key[3]] + a)) & 0xFF;
            key[3] = (key[3] - (key[0] - shiftKey[a])) & 0xFF;
            let r = key[0] | (key[1] << 8) | (key[2] << 16) | (key[3] << 24);
            r = (r << 3) | (r >>> 29);
            key[0] = r & 0xFF;
            key[1] = (r >>> 8) & 0xFF;
            key[2] = (r >>> 16) & 0xFF;
            key[3] = (r >>> 24) & 0xFF;
        }
        return key;
    }

    createPacketHeader(length: number): Buffer {
        let a = (this.iv[3] & 0xff);
        a |= (this.iv[2] << 8) & 0xff00;
        a ^= this.mapleVersion;
        const b = a ^ (((length << 8) & 0xff00) | length >>> 8);
        const header = Buffer.from([
            (a >>> 8) & 0xff,
            a & 0xff,
            (b >>> 8) & 0xff,
            b & 0xff
        ]);
        return header;
    }

    transform(data: Uint8Array): void {
        if (data.length === 0) return;
        let remaining = data.length;
        let chunkLimit = 0x5B0;
        let offset = 0;
        const block = new Uint8Array(16);
        while (remaining > 0) {
            // Fill block with IV repeated to 16 bytes
            for (let i = 0; i < 16; i += 4) {
                block[i] = this.iv[0];
                block[i+1] = this.iv[1];
                block[i+2] = this.iv[2];
                block[i+3] = this.iv[3];
            }
            const chunkLen = remaining < chunkLimit ? remaining : chunkLimit;
            for (let i = offset; i < offset + chunkLen; i++) {
                const blockIndex = (i - offset) % 16;
                if (blockIndex === 0) {
                    const ecb = new aesjs.ModeOfOperation.ecb(key);
                    block.set(ecb.encrypt(block));
                }
                data[i] ^= block[blockIndex];
            }
            offset += chunkLen;
            remaining -= chunkLen;
            chunkLimit = 0x5B4;
        }
        this.iv = this.morphIV(this.iv);
    }
}
